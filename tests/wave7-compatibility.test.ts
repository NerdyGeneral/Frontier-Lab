import { historicalContent, loadHistoricalSnapshot } from './fixtures/historical-rules';
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { GameState } from '../src/contracts/types';
import { CONTENT } from '../src/content/catalog';
import { advanceWeek } from '../src/core/engine';
import { canonicalStateHash } from '../src/core/canonical';
import { deserializeState, serializeState } from '../src/core/snapshot';
import { validateState } from '../src/core/validation';

// A naturally played Week 269 business from the published Wave 6 engine.
// The oracle was generated by that exact Git revision, not this implementation.
const raw = readFileSync(join(__dirname, 'fixtures/wave6-snapshot.json'), 'utf8');
const envelope = () => JSON.parse(raw) as { checksum: string; schemaVersion: number; contentVersion: string; state: GameState };
const oracle = JSON.parse(readFileSync(join(__dirname, 'fixtures/wave6-expected.json'), 'utf8')) as {
  sourceCommit: string; sourceContent: string; checksum: string;
  weeks: { week: number; hash: string; cashCents: number; revenueCents: number; expenseCents: number; trustBps: number;
    contracts: { id: string; termIndex: number; termWeeksServed: number; lifetimeBilledCents: number }[] }[];
};
function load() { const result = deserializeState(raw); assert.ok(result.ok, result.ok ? '' : result.error); return result; }
const loadHistorical = () => loadHistoricalSnapshot(raw);

test('W7-S01: published Wave 6 import adds the announced market calendar and preserves all paid progress', () => {
  const previous = envelope(), current = load();
  assert.equal(oracle.sourceCommit, '870fd3792f162542740c53d7df154d52f8917c5f');
  assert.equal(previous.checksum, '4246bec5'); assert.equal(previous.checksum, oracle.checksum);
  assert.equal(previous.checksum, canonicalStateHash(previous.state));
  assert.equal(previous.schemaVersion, 5); assert.equal(previous.contentVersion, '0.7.0');
  assert.equal(current.migratedFrom, 7); assert.equal(current.state.week, 269);
  assert.deepEqual(current.state, { ...previous.state, contentVersion: CONTENT.version, buildVersion: CONTENT.buildVersion,
    slices: { ...previous.state.slices, markets: { ...previous.state.slices.markets, opportunityCalendar: { startedWeek: previous.state.week, sequenceVersion: 2 as const } } } });
  assert.deepEqual(validateState(current.state, CONTENT), []);
  assert.equal(current.state.queuedCommands[0].payload.kind, 'review_agent_job');
  const job = Object.values(current.state.slices.agents.jobs).find(job => job.companyId === current.state.playerCompanyId)!;
  assert.equal(job.status, 'awaiting-approval');
  assert.equal(job.recovery, undefined);
  assert.equal(job.model.planner, undefined);
});

test('W7-S02: twelve ordinary weeks exactly match the published state, including approval, paid action/audit and a license renewal', () => {
  let state = loadHistorical().state;
  for (const expected of oracle.weeks) {
    const result = advanceWeek(state, historicalContent(state)); assert.ok(result.accepted, result.reason?.message); state = result.state;
    const normalized = { ...state, contentVersion: oracle.sourceContent, buildVersion: oracle.sourceContent };
    assert.equal(canonicalStateHash(normalized), expected.hash, 'Published outcome changed in Week ' + expected.week);
    const company = state.slices.company.companies[state.playerCompanyId];
    assert.equal(company.cashCents, expected.cashCents); assert.equal(company.lastWeek.revenueCents, expected.revenueCents);
    for (const contract of expected.contracts) {
      const actual = state.slices.products.commercialContracts[contract.id];
      assert.equal(actual.termIndex, contract.termIndex); assert.equal(actual.termWeeksServed, contract.termWeeksServed);
      assert.equal(actual.lifetimeBilledCents, contract.lifetimeBilledCents);
    }
  }
  assert.equal(oracle.weeks.at(-1)!.contracts[0].termIndex, oracle.weeks[0].contracts[0].termIndex + 1);
});

test('W7-S03: upgraded saves round trip and continue deterministically without repeated migration', () => {
  let left = load().state;
  const restored = deserializeState(serializeState(left, historicalContent(left)), historicalContent(left)); assert.ok(restored.ok, restored.ok ? '' : restored.error);
  assert.equal(restored.migratedFrom, undefined); let right = restored.state;
  for (let n = 0; n < 3; n++) {
    const a = advanceWeek(left, historicalContent(left)), b = advanceWeek(right, historicalContent(right)); assert.ok(a.accepted, a.reason?.message); assert.ok(b.accepted, b.reason?.message);
    left = a.state; right = b.state; assert.equal(canonicalStateHash(left), canonicalStateHash(right));
  }
});

test('W7-S04: checksum corruption and new research hidden behind a Wave 6 header are rejected', () => {
  const corrupt = envelope(); corrupt.state.slices.company.companies[corrupt.state.playerCompanyId].cashCents++;
  const invalid = deserializeState(JSON.stringify(corrupt)); assert.equal(invalid.ok, false);
  if (!invalid.ok) assert.match(invalid.error, /checksum/);
  for (const researchId of ['R4B', 'R9A', 'R10A', 'R11A']) {
    const forged = envelope(); forged.state.slices.research.completedByCompany[forged.state.playerCompanyId].push(researchId);
    forged.checksum = canonicalStateHash(forged.state);
    const result = deserializeState(JSON.stringify(forged)); assert.equal(result.ok, false);
  }
  assert.equal(canonicalStateHash(envelope().state), oracle.checksum);
});


test('W7-S05: new optional commands cannot hide behind Wave 6 content headers', () => {
  for (const payload of [
    { kind: 'start_training', baseModelId: CONTENT.seedModel.id, packetId: CONTENT.starterData.id, asAdapter: false },
    { kind: 'start_training', baseModelId: CONTENT.seedModel.id, packetId: CONTENT.starterData.id, recipeId: 'planner-curriculum' },
    { kind: 'evaluate_model', modelId: 'model-natural-business-command-159', suiteId: 'independent-holdouts-1' },
    { kind: 'start_system_rollout', method: 'adapter-bank' },
    { kind: 'start_system_rollout', method: 'action-receipts' },
    { kind: 'recover_agent_job', jobId: 'agent:0e424a52:support-replies:66', maxSteps: 24, workBudget: 32_000_000_000 },
  ]) {
    const forged = envelope();
    forged.state.queuedCommands = [{ id: 'old-header-new-method', companyId: forged.state.playerCompanyId, issuedForWeek: forged.state.week + 1, reservedCents: 0, payload: payload as GameState['queuedCommands'][number]['payload'] }];
    forged.checksum = canonicalStateHash(forged.state);
    const result = deserializeState(JSON.stringify(forged));
    assert.equal(result.ok, false);
    if (!result.ok) assert.match(result.error, /unavailable in that build/);
  }
});
