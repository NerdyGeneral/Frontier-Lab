test('W1-M03: migration is pure and deterministic; re-saving is an ordinary v2 restore', () => {
  const input = legacyEnvelope().state, before = structuredClone(input);
  const first = migrateWave0State(input, CONTENT), second = migrateWave0State(input, CONTENT);
  assert.ok(first.ok, first.ok ? '' : first.error); assert.deepEqual(input, before); assert.deepEqual(first, second);
  const text = serializeState(first.state), envelope = JSON.parse(text);
  assert.equal(envelope.schemaVersion, 5); assert.equal(envelope.contentVersion, CONTENT.version);
  assert.equal(envelope.checksum, canonicalStateHash(first.state));
  const restored = deserializeState(text);
  assert.ok(restored.ok, restored.ok ? '' : restored.error);
  assert.equal(restored.migratedFrom, undefined); assert.deepEqual(restored.state, first.state);
});

test('W1-M04: the next week executes preserved queued commands and scheduled deliveries exactly once', () => {
  const original = legacyEnvelope().state, state = migrated().state;
  const fourth = advanceWeek(state);
  assert.ok(fourth.accepted, fourth.reason?.message);
  assert.equal(fourth.state.week, 4); assert.equal(fourth.state.revision, state.revision + 1);
  assert.equal(fourth.state.slices.company.companies[state.playerCompanyId].name, 'Legacy queued rename');
  assert.equal(fourth.state.slices.company.companies[state.playerCompanyId].cashCents, 4_400_000);
  assert.equal(fourth.state.queuedCommands.length, 0);
  for (const command of original.queuedCommands) assert.equal(fourth.state.commandReceipts[command.id].status, 'accepted');
  const fleet = fourth.state.slices.compute.fleets[state.playerCompanyId];
  assert.deepEqual(fleet.allocation, { serving: 1_000_000_000, development: 3_000_000_000, research: 0 });
  assert.deepEqual(fleet.deliveredEquipmentIds, ['legacy-gpu-order']);
  assert.deepEqual(fleet.inventory['legacy-gpu-order'], { cu: 2_000_000_000, memoryMU: 4_000_000_000, arrivedWeek: 4 });
  assert.equal(fleet.ownedCU, 0, 'A retained equipment delivery does not bypass later installation.');
  assert.deepEqual(fourth.state.random, original.random);
  assert.deepEqual(fourth.state.scheduled.map(item => item.id), ['legacy-model-release']);
  assert.equal(fourth.state.slices.company.ledger.filter(e => e.companyId === state.playerCompanyId).length, original.slices.company.ledger.length + 2);
  const fifth = advanceWeek(fourth.state);
  assert.ok(fifth.accepted, fifth.reason?.message);
  assert.equal(fifth.state.slices.models.versions[CONTENT.seedModel.id].status, 'released');
  assert.equal(fifth.state.scheduled.length, 0);
  assert.deepEqual(fifth.state.slices.compute.fleets[state.playerCompanyId].deliveredEquipmentIds, ['legacy-gpu-order']);
  assert.equal(fifth.state.slices.company.companies[state.playerCompanyId].cashCents, 4_300_000);
  assert.deepEqual(fifth.state.random, original.random);
});

test('W1-M05: original checksum is checked before old validation or migration', () => {
  const envelope = legacyEnvelope();
  envelope.state.slices.company.companies[envelope.state.playerCompanyId].cashCents = -1;
  const corrupt = JSON.stringify(envelope), rejected = deserializeState(corrupt);
  assert.equal(rejected.ok, false);
  if (!rejected.ok) assert.match(rejected.error, /checksum/i);
  assert.equal(JSON.stringify(envelope), corrupt, 'Rejected input must remain exportable without edits.');
  const structurallyInvalid = deserializeState(withChecksum(envelope));
  assert.equal(structurallyInvalid.ok, false);
  if (!structurallyInvalid.ok) assert.match(structurallyInvalid.error, /Wave 0 save failed validation/i);
});

test('W1-M06: unknown versions and header/state mismatches cannot be auto-upgraded', () => {
  for (const [schema, content] of [[6, CONTENT.version], [1, '0.1.1'], [0, '0.1.0']] as const) {
    const envelope = legacyEnvelope();
    envelope.schemaVersion = schema; envelope.contentVersion = content;
    envelope.state.schemaVersion = schema; envelope.state.contentVersion = content;
    const result = deserializeState(withChecksum(envelope));
    assert.equal(result.ok, false); if (!result.ok) assert.match(result.error, /not supported/i);
  }
  const mismatched = legacyEnvelope(); mismatched.state.schemaVersion = 2;
  assert.equal(deserializeState(withChecksum(mismatched)).ok, false);
  const futureTarget = structuredClone(CONTENT); futureTarget.version = '99.0.0';
  assert.equal(migrateWave0State(legacyEnvelope().state, futureTarget).ok, false);
});

test('W1-M07: a v2 save with downgraded headers is not accepted as authentic legacy data', () => {
  const state = createInitialState(); state.schemaVersion = 1; state.contentVersion = '0.1.0'; state.buildVersion = '0.1.0';
  const text = JSON.stringify({ format: 'frontier-lab', schemaVersion: 1, contentVersion: '0.1.0', checksum: canonicalStateHash(state), state });
  const result = deserializeState(text);
  assert.equal(result.ok, false); if (!result.ok) assert.match(result.error, /Specialist commissions and varied campaign schedules do not belong to this historical save version/);
});

test('W1-M08: new validation rejects incompatible legacy records without silently resetting them', () => {
  const envelope = legacyEnvelope();
  envelope.state.slices.products.activeIds.push('orphaned-old-product');
  assert.deepEqual(validateLegacyState(envelope.state, legacyContent), [], 'The old validator allowed this unsupported future product reference.');
  const before = structuredClone(envelope.state), result = deserializeState(withChecksum(envelope));
  assert.equal(result.ok, false); if (!result.ok) assert.match(result.error, /save failed validation/i);
  assert.deepEqual(envelope.state, before);
});
