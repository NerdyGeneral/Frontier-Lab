test('W2-S06: migrated inflight commands retain published-source work, hiring charges, onboarding and finite completion across three real weeks', () => {
  const loaded = deserializeState(inflightRaw); assert.ok(loaded.ok, loaded.ok ? '' : loaded.error);
  const old = inflight(), id = loaded.state.playerCompanyId;
  const roundTrip = deserializeState(serializeState(loaded.state)); assert.ok(roundTrip.ok, roundTrip.ok ? '' : roundTrip.error);
  let state = roundTrip.state;
  for (const expected of inflightExpected.trace) {
    const result = advanceWeek(state); assert.ok(result.accepted, result.reason?.message); state = result.state;
    const company = state.slices.company.companies[id], run = state.slices.models.trainingRuns[inflightExpected.runId], fleet = state.slices.compute.fleets[id];
    const work = { status: run.status, completedWork: run.completedWork, physicalWork: run.physicalWork,
      checkpointWork: run.checkpointWork, checkpointModelId: run.checkpointModelId, lastProgress: run.lastProgress,
      ...(run.completedWeek === undefined ? {} : { completedWeek: run.completedWeek }) };
    assert.equal(state.week, expected.week);
    assert.equal(company.cashCents, expected.cashCents); assert.deepEqual(company.lastWeek, expected.lastWeek);
    assert.deepEqual(work, expected.work); assert.deepEqual(run.evidence, old.state.slices.models.trainingRuns[inflightExpected.runId].evidence);
    assert.deepEqual(fleet.allocation, expected.allocation); assert.deepEqual(fleet.lastWork, expected.executedWork);
    const charges = state.slices.company.ledger.filter(entry => entry.companyId === id && entry.week === state.week)
      .map(({ id: factId, amountCents, paidCents, unpaidCents, sourceId, category, kind }) => ({ id: factId, amountCents, paidCents, unpaidCents, sourceId, category, kind }));
    assert.deepEqual(charges.sort((a, b) => a.id.localeCompare(b.id)), [...expected.postedThisWeek].sort((a, b) => a.id.localeCompare(b.id)));
    assert.equal(state.slices.models.versions[inflightExpected.checkpointId].status, expected.checkpointStatus);
    assert.equal(Object.values(state.slices.company.staff).filter(staff => staff.companyId === id && staff.role === 'data' && staff.readyWeek <= state.week).length, expected.readyDataStaff);
    const model = state.slices.models.versions[run.outputModelId];
    if (expected.model) {
      assert.ok(model);
      const outcome = { capabilityBps: model.capabilityBps, reliabilityBps: model.reliabilityBps, residentMU: model.residentMU,
        family: model.family, architecture: model.architecture, status: model.status, parentModelId: model.parentModelId, trainingRunId: model.trainingRunId };
      assert.deepEqual(outcome, expected.model);
    } else assert.equal(model, undefined);
    // Rivals may draw on their own streams; preserved player evidence never rerolls.
    for (const [stream, saved] of Object.entries(old.state.random)) assert.deepEqual(state.random[stream], saved);
    for (const [reportId, report] of Object.entries(old.state.slices.models.reports)) assert.deepEqual(state.slices.models.reports[reportId], report);
  }
  for (const command of old.state.queuedCommands) assert.equal(state.commandReceipts[command.id].status, 'accepted');
  assert.equal(state.slices.company.ledger.filter(entry => entry.id === 'recruit:fixture-data-hire').length, 1);
  assert.equal(state.queuedCommands.filter(command => command.companyId === id).length, 0);
});
