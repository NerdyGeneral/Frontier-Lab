const original = readFileSync(join(__dirname, 'fixtures/wave1-snapshot.json'), 'utf8');
const envelope = () => JSON.parse(original) as { state: GameState; checksum: string; schemaVersion: number; contentVersion: string; format: string };
function upgraded() { const r = deserializeState(original); assert.ok(r.ok, r.ok ? '' : r.error); return r; }

// Generated by executing git archive a74d3b3a804d062d3bb29764604c59a0361780e8,
// not by downgrading this build: prepare data, hire ML, train to 6/12 CUw,
// pause and evaluate its midpoint, then queue resume/allocation/data hiring.
const inflightRaw = readFileSync(join(__dirname, 'fixtures/wave1-inflight-snapshot.json'), 'utf8');
const inflight = () => JSON.parse(inflightRaw) as ReturnType<typeof envelope>;
type InflightTrace = {
  week: number; cashCents: number; lastWeek: CompanyRecord['lastWeek'];
  work: Pick<TrainingRun, 'status' | 'completedWork' | 'physicalWork' | 'checkpointWork' | 'checkpointModelId' | 'lastProgress' | 'completedWeek'>;
  allocation: Allocation; executedWork: Allocation;
  postedThisWeek: Pick<LedgerEntry, 'id' | 'amountCents' | 'paidCents' | 'unpaidCents' | 'sourceId' | 'category' | 'kind'>[];
  model: Pick<ModelVersion, 'capabilityBps' | 'reliabilityBps' | 'residentMU' | 'family' | 'architecture' | 'status' | 'parentModelId' | 'trainingRunId'> | null;
  checkpointStatus: ModelVersion['status']; readyDataStaff: number;
};
const inflightExpected = JSON.parse(readFileSync(join(__dirname, 'fixtures/wave1-inflight-expected.json'), 'utf8')) as {
  sourceCommit: string; sourceSchema: number; sourceContent: string; snapshotChecksum: string; runId: string; checkpointId: string; trace: InflightTrace[];
};

test('W2-S01: authentic first-sale Wave 1 snapshot upgrades without changing player history, time, IDs or randomness', () => {
  const old = envelope();
  assert.equal(old.checksum, canonicalStateHash(old.state));
  assert.deepEqual(validateLegacyWave1State(old.state, { ...CONTENT, version: '0.2.0' }), []);
  const result = upgraded(), s = result.state, id = s.playerCompanyId;
  assert.equal(result.migratedFrom, 2); assert.equal(s.schemaVersion, 5); assert.equal(s.contentVersion, CONTENT.version);
  for (const key of ['week','revision','nextId','seed','random','queuedCommands','commandReceipts','scheduled','journal','lastTick'] as const) assert.deepEqual(s[key], old.state[key]);
  assert.deepEqual(s.slices.company.companies[id], old.state.slices.company.companies[id]);
  assert.deepEqual(s.slices.company.ledger, old.state.slices.company.ledger);
  assert.deepEqual(s.slices.company.postedFacts, old.state.slices.company.postedFacts);
  for (const key of ['trainingRuns','evaluationRuns'] as const) assert.deepEqual(s.slices.models[key], old.state.slices.models[key]);
  for (const [key, report] of Object.entries(old.state.slices.models.reports)) assert.deepEqual(s.slices.models.reports[key], report);
  assert.equal(s.slices.markets.cohorts.filter(c => c.companyId === id).reduce((n,c) => n+c.count,0), 18);
  assert.equal(s.slices.markets.trials.filter(c => c.companyId === id).reduce((n,c) => n+c.count,0), 20);
  assert.deepEqual(validateState(s, CONTENT), []);
});

test('W2-S02: migration is deterministic, seeds each rival once, and replay survives a current snapshot', () => {
  const a = upgraded(), b = upgraded(); assert.deepEqual(a, b);
  assert.equal(a.state.slices.markets.activeRivalIds.length, 3);
  const loaded = deserializeState(serializeState(a.state)); assert.ok(loaded.ok, loaded.ok ? '' : loaded.error);
  assert.equal(loaded.migratedFrom, undefined);
  let left = a.state, right = loaded.state;
  for (let week = 0; week < 6; week++) { const x = advanceWeek(left), y = advanceWeek(right); assert.ok(x.accepted, x.reason?.message); assert.ok(y.accepted, y.reason?.message); left = x.state; right = y.state; assert.equal(canonicalStateHash(left), canonicalStateHash(right)); }
  assert.equal(left.slices.markets.activeRivalIds.length, 3);
});

test('W2-S03: a large legacy cohort is split across finite segments without deleting accounts, IDs or partial trial progress', () => {
  const data = envelope(), old = data.state, id = old.playerCompanyId;
  old.slices.markets.cohorts[0].count = 1900;
  old.slices.markets.payingConsumers = old.slices.markets.cohorts.reduce((n,c) => n+c.count,0);
  old.slices.markets.trials[0].workCompleted = 123456;
  data.checksum = canonicalStateHash(old);
  const r = deserializeState(JSON.stringify(data)); assert.ok(r.ok, r.ok ? '' : r.error);
  const market = r.state.slices.markets;
  assert.equal(market.cohorts.filter(c => c.companyId === id).reduce((n,c) => n+c.count,0), old.slices.markets.payingConsumers);
  assert.equal(market.trials.filter(c => c.companyId === id).reduce((n,c) => n+c.count,0), 20);
  assert.equal(market.trials.filter(c => c.companyId === id).reduce((n,c) => n+c.workCompleted,0), 123456);
  for (const c of old.slices.markets.cohorts) assert.ok(market.cohorts.some(next => next.id === c.id));
  for (const t of old.slices.markets.trials) assert.ok(market.trials.some(next => next.id === t.id));
  for (const segment of MARKET_SEGMENTS) assert.ok(market.cohorts.filter(c => c.segmentId === segment.id).reduce((n,c) => n+c.count,0) + market.trials.filter(c => c.segmentId === segment.id).reduce((n,c) => n+c.count,0) <= segment.population);
});

test('W2-S04: changed checksums, fake legacy headers and invalid old references cannot bypass migration validation', () => {
  const broken = envelope(); broken.state.week += 1;
  const result = deserializeState(JSON.stringify(broken)); assert.equal(result.ok, false); if (!result.ok) assert.match(result.error, /checksum/);
  const fake = createInitialState(); fake.schemaVersion = 2; fake.contentVersion = '0.2.0';
  const rejected = deserializeState(JSON.stringify({ format: 'frontier-lab', schemaVersion: 2, contentVersion: '0.2.0', state: fake, checksum: canonicalStateHash(fake) }));
  assert.equal(rejected.ok, false); if (!rejected.ok) assert.match(rejected.error, /Specialist commissions and varied campaign schedules do not belong to this historical save version/);
  const orphan = envelope(); orphan.state.slices.markets.cohorts[0].productId = 'missing'; orphan.checksum = canonicalStateHash(orphan.state);
  assert.equal(deserializeState(JSON.stringify(orphan)).ok, false);
});

